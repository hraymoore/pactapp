const CERT_DIR = process.env.PACT_PAYMENT_CERT_DIR || path.join(__dirname, "..", "..", "data", "payment-certificates");
fs.mkdirSync(CERT_DIR, { recursive: true });

const STATUS_LABEL = {
  unpaid: "Unpaid",
  partially_paid: "Partial Payment",
  paid_in_full: "Paid in Full",
  refunded: "Refunded",
  disputed: "Disputed",
};

function findPartyUser(party) {
  if (!party) return null;
  return db.prepare("SELECT * FROM users WHERE email = ?").get(party.email) || null;
}

// The two parties a contract's payment terms can possibly be between are
// its owner and its one counterparty — group contracts/milestone payers
// are out of scope here, matching the Phase-2 note on milestone structures.
function getContractParties(contractId) {
  const parties = db.prepare("SELECT * FROM contract_parties WHERE contract_id = ?").all(contractId);
  const owner = parties.find((p) => p.role === "owner");
  const counterparty = parties.find((p) => p.role === "counterparty");
  return { owner, counterparty, parties };
}

const PAYMENT_TERMS_START = "\n\n--- PAYMENT TERMS (generated by Pact; edit via the Payment panel, not this text) ---\n";
const PAYMENT_TERMS_END = "\n--- END PAYMENT TERMS ---";

function renderPaymentTermsBlock({ totalAmountCents, currency, structure, depositAmountCents, dueDate, closeOnFullPayment, payeeName, payerName }) {
  const fmt = (c) => `${(c / 100).toFixed(2)} ${currency.toUpperCase()}`;
  const lines = [
    `Payee: ${payeeName}`,
    `Payer: ${payerName}`,
    `Total amount due: ${fmt(totalAmountCents)}`,
  ];
  if (structure === "deposit_plus_balance") {
    lines.push(`Deposit due at signing: ${fmt(depositAmountCents)}`);
    lines.push(`Remaining balance: ${fmt(totalAmountCents - depositAmountCents)}`);
  }
  if (dueDate) lines.push(`Due date: ${dueDate}`);
  lines.push(
    closeOnFullPayment
      ? "This contract will automatically close once payment is received in full."
      : "This contract will remain active after payment is received in full."
  );
  lines.push(
    "Payment is processed through Stripe. Pact is a technology platform, not a payment processor, bank, or escrow agent, and does not adjudicate disputes over work quality — see the Payments section of the Terms of Service."
  );
  return PAYMENT_TERMS_START + lines.join("\n") + PAYMENT_TERMS_END;
}

// Inserts or replaces the auto-generated payment-terms block inside a
// contract's body so the terms are literally part of what both parties
// read and sign — not just metadata sitting next to the contract. Only
// ever called before signature (routes/payments.js enforces that); after
// signature, this block is frozen along with the rest of the body by the
// same lock that already protects every other clause.
function injectPaymentTermsIntoBody(body, block) {
  const startIdx = body.indexOf(PAYMENT_TERMS_START);
  if (startIdx === -1) return body + block;
  const endIdx = body.indexOf(PAYMENT_TERMS_END, startIdx);
  if (endIdx === -1) return body + block;
  return body.slice(0, startIdx) + block + body.slice(endIdx + PAYMENT_TERMS_END.length);
}

function setPaymentTerms(contract, input, actingUser) {
  if (contract.status === "signed" || contract.status === "closed") {
    const err = new Error(
      "Payment terms are locked once a contract is signed — changing them requires a signed amendment, which isn't built yet."
    );
    err.status = 409;
    throw err;
  }

  const totalAmountCents = Number(input.totalAmountCents);
  if (!Number.isInteger(totalAmountCents) || totalAmountCents <= 0) {
    const err = new Error("Total amount must be a positive whole number of cents.");
    err.status = 400;
    throw err;
  }
  const structure = input.structure === "deposit_plus_balance" ? "deposit_plus_balance" : "single";
  let depositAmountCents = null;
  if (structure === "deposit_plus_balance") {
    depositAmountCents = Number(input.depositAmountCents);
    if (!Number.isInteger(depositAmountCents) || depositAmountCents <= 0 || depositAmountCents >= totalAmountCents) {
      const err = new Error("Deposit amount must be a positive whole number of cents less than the total.");
      err.status = 400;
      throw err;
    }
  }
  if (input.dueDate && !/^\d{4}-\d{2}-\d{2}$/.test(input.dueDate)) {
    const err = new Error("Due date must be in YYYY-MM-DD format.");
    err.status = 400;
    throw err;
  }

  const { owner, counterparty } = getContractParties(contract.id);
  if (!counterparty) {
    const err = new Error("This contract needs a counterparty before payment terms can be set.");
    err.status = 400;
    throw err;
  }
  const payeeEmail = String(input.payeeEmail || "").trim().toLowerCase();
  let payeeParty, payerParty;
  if (owner && payeeEmail === owner.email.toLowerCase()) {
    payeeParty = owner;
    payerParty = counterparty;
  } else if (payeeEmail === counterparty.email.toLowerCase()) {
    payeeParty = counterparty;
    payerParty = owner;
  } else {
    const err = new Error("The payee must be one of this contract's two parties.");
    err.status = 400;
    throw err;
  }

  const currency = (input.currency || "usd").toLowerCase();
  const closeOnFullPayment = !!input.closeOnFullPayment;
  const block = renderPaymentTermsBlock({
    totalAmountCents,
    currency,
    structure,
    depositAmountCents,
    dueDate: input.dueDate || null,
    closeOnFullPayment,
    payeeName: payeeParty.name,
    payerName: payerParty.name,
  });
  const nextBody = injectPaymentTermsIntoBody(contract.body, block);

  db.prepare(
    `INSERT INTO contract_payment_terms
       (contract_id, total_amount_cents, currency, structure, deposit_amount_cents, due_date, close_on_full_payment, payee_party_id, payer_party_id, updated_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, datetime('now'))
     ON CONFLICT(contract_id) DO UPDATE SET
       total_amount_cents = excluded.total_amount_cents,
       currency = excluded.currency,
       structure = excluded.structure,
       deposit_amount_cents = excluded.deposit_amount_cents,
       due_date = excluded.due_date,
       close_on_full_payment = excluded.close_on_full_payment,
       payee_party_id = excluded.payee_party_id,
       payer_party_id = excluded.payer_party_id,
       updated_at = datetime('now')`
  ).run(
    contract.id,
    totalAmountCents,
    currency,
    structure,
    depositAmountCents,
    input.dueDate || null,
    closeOnFullPayment ? 1 : 0,
    payeeParty.id,
    payerParty.id
  );
  db.prepare("UPDATE contracts SET body = ?, content_hash = ?, updated_at = datetime('now') WHERE id = ?").run(
    nextBody,
    contentHash(nextBody),
    contract.id
  );
  logAudit(
    contract.id,
    actingUser,
    "payment_terms_set",
    `Payment terms set: ${payeeParty.name} to be paid ${(totalAmountCents / 100).toFixed(2)} ${currency.toUpperCase()} by ${payerParty.name}.`
  );

  return getPaymentTerms(contract.id);
}

function getPaymentTerms(contractId) {
  return db.prepare("SELECT * FROM contract_payment_terms WHERE contract_id = ?").get(contractId) || null;
}

function nextAmountDueCents(terms, amountPaidCents) {
  if (terms.structure === "deposit_plus_balance" && amountPaidCents < terms.deposit_amount_cents) {
    return terms.deposit_amount_cents - amountPaidCents;
  }
  return Math.max(terms.total_amount_cents - amountPaidCents, 0);
}

// Append-only insert. The UNIQUE constraint on stripe_event_id is the real
// idempotency guard — a retried webhook delivery throws here and the
// caller (routes/billing.js) treats that specific error as an
// already-processed no-op, same pattern already used for purchases.
function recordPaymentEvent({
  contractId,
  eventType,
  stripeEventId = null,
  stripePaymentIntentId = null,
  amountCents = 0,
  currency = "usd",
  payerUserId = null,
  payeeUserId = null,
  rawStatus = null,
  source = "stripe",
  createdByUserId = null,
  createdByIp = null,
}) {
  const info = db
    .prepare(
      `INSERT INTO payment_events
         (contract_id, event_type, stripe_event_id, stripe_payment_intent_id, amount_cents, currency, payer_user_id, payee_user_id, raw_status, source, created_by_user_id, created_by_ip)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`
    )
    .run(
      contractId,
      eventType,
      stripeEventId,
      stripePaymentIntentId,
      amountCents,
      currency,
      payerUserId,
      payeeUserId,
      rawStatus,
      source,
      createdByUserId,
      createdByIp
    );
  return db.prepare("SELECT * FROM payment_events WHERE id = ?").get(info.lastInsertRowid);
}

const CREDIT_EVENTS = new Set(["payment_succeeded", "off_platform_confirmed"]);
const DEBIT_EVENTS = new Set(["refunded", "dispute_lost"]);

// The single source of truth for contracts.payment_status/amount_paid_cents
// — always derived fresh from the payment_events ledger rather than
// incremented in place, so a bug anywhere else can't leave the two out of
// sync. An unresolved dispute overrides the ledger-derived status (the
// money's status is genuinely unsettled), which is why dispute_created/
// dispute_won/dispute_lost carry zero amount and never feed the sum below.
function recomputeContractPaymentStatus(contractId) {
  const terms = getPaymentTerms(contractId);
  const contract = db.prepare("SELECT * FROM contracts WHERE id = ?").get(contractId);
  if (!terms || !contract) return;

  const events = db.prepare("SELECT * FROM payment_events WHERE contract_id = ? ORDER BY id ASC").all(contractId);
  let net = 0;
  let everHadDebit = false;
  let openDisputes = 0;
  for (const e of events) {
    if (CREDIT_EVENTS.has(e.event_type)) net += e.amount_cents;
    if (DEBIT_EVENTS.has(e.event_type)) {
      net -= e.amount_cents;
      everHadDebit = true;
    }
    if (e.event_type === "dispute_created") openDisputes += 1;
    if (e.event_type === "dispute_won" || e.event_type === "dispute_lost") openDisputes -= 1;
  }
  net = Math.max(net, 0);

  let status;
  if (openDisputes > 0) {
    status = "disputed";
  } else if (net <= 0) {
    status = everHadDebit ? "refunded" : "unpaid";
  } else if (net >= terms.total_amount_cents) {
    status = "paid_in_full";
  } else {
    status = "partially_paid";
  }

  db.prepare("UPDATE contracts SET payment_status = ?, amount_paid_cents = ? WHERE id = ?").run(status, net, contractId);

  if (status === "paid_in_full" && terms.close_on_full_payment && contract.status === "signed") {
    db.prepare("UPDATE contracts SET status = 'closed', closed_reason = 'paid_in_full' WHERE id = ?").run(contractId);
    logAudit(contractId, null, "closed", "Contract automatically closed — payment received in full.");
  }

  return status;
}

function reopenIfDisputed(contractId) {
  const contract = db.prepare("SELECT * FROM contracts WHERE id = ?").get(contractId);
  if (contract && contract.status === "closed" && contract.closed_reason === "paid_in_full") {
    db.prepare("UPDATE contracts SET status = 'signed', reopened_reason = 'payment_disputed' WHERE id = ?").run(contractId);
    logAudit(contractId, null, "reopened", "Contract reopened — a payment dispute was filed on a previously fully-paid contract.");
  }
}

function emailBothParties(contractId, { subject, text }) {
  const { owner, counterparty } = getContractParties(contractId);
  [owner, counterparty].filter(Boolean).forEach((p) => sendMail({ to: p.email, subject, text }));
}

// Builds and stores the Payment Certificate PDF for one successful
// (full or partial) payment event. Never called for a refund/dispute —
// those are recorded in the ledger and surfaced as a banner on the
// contract instead of altering or regenerating this certificate.
async function issueCertificateForEvent(event) {
  const contract = db.prepare("SELECT * FROM contracts WHERE id = ?").get(event.contract_id);
  const terms = getPaymentTerms(event.contract_id);
  const { owner, counterparty } = getContractParties(event.contract_id);
  const payeeParty = terms && terms.payee_party_id === owner.id ? owner : counterparty;
  const payerParty = payeeParty === owner ? counterparty : owner;

  const remainingCents = Math.max((terms ? terms.total_amount_cents : 0) - contract.amount_paid_cents, 0);
  const dataFields = {
    contractId: contract.id,
    contractName: contract.name,
    payerName: payerParty.name,
    payeeName: payeeParty.name,
    amountCents: event.amount_cents,
    currency: event.currency,
    remainingCents,
    occurredAtUtc: event.occurred_at,
    stripePaymentIntentId: event.stripe_payment_intent_id,
    statusLabel: STATUS_LABEL[contract.payment_status] || contract.payment_status,
  };
  const dataHash = crypto.createHash("sha256").update(JSON.stringify(dataFields), "utf8").digest("hex");

  const pdfBytes = await renderPaymentCertificatePdf({ ...dataFields, dataHash });
  const fileName = `${crypto.randomBytes(20).toString("hex")}.pdf`;
  fs.writeFileSync(path.join(CERT_DIR, fileName), Buffer.from(pdfBytes));

  const info = db
    .prepare(
      "INSERT INTO payment_certificates (contract_id, payment_event_id, pdf_file_ref, data_hash) VALUES (?, ?, ?, ?)"
    )
    .run(event.contract_id, event.id, fileName, dataHash);
  return db.prepare("SELECT * FROM payment_certificates WHERE id = ?").get(info.lastInsertRowid);
}

// ---- Stripe webhook handlers (routes/billing.js dispatches into these) ----

async function handlePaymentIntentSucceeded(paymentIntent, stripeEventId) {
  const contractId = Number(paymentIntent.metadata && paymentIntent.metadata.contractId);
  if (!contractId) return;
  const event = recordPaymentEvent({
    contractId,
    eventType: "payment_succeeded",
    stripeEventId,
    stripePaymentIntentId: paymentIntent.id,
    amountCents: paymentIntent.amount_received,
    currency: paymentIntent.currency,
    payerUserId: paymentIntent.metadata.payerUserId ? Number(paymentIntent.metadata.payerUserId) : null,
    payeeUserId: paymentIntent.metadata.payeeUserId ? Number(paymentIntent.metadata.payeeUserId) : null,
    rawStatus: paymentIntent.status,
    source: "stripe",
  });
  recomputeContractPaymentStatus(contractId);
  const contract = db.prepare("SELECT * FROM contracts WHERE id = ?").get(contractId);
  await issueCertificateForEvent(event);
  emailBothParties(contractId, {
    subject: `Payment received: ${contract.name}`,
    text: `A payment of ${(event.amount_cents / 100).toFixed(2)} ${event.currency.toUpperCase()} was received on "${contract.name}". Status: ${STATUS_LABEL[contract.payment_status]}.`,
  });
}

function handlePaymentIntentFailed(paymentIntent, stripeEventId) {
  const contractId = Number(paymentIntent.metadata && paymentIntent.metadata.contractId);
  if (!contractId) return;
  recordPaymentEvent({
    contractId,
    eventType: "payment_failed",
    stripeEventId,
    stripePaymentIntentId: paymentIntent.id,
    amountCents: 0,
    currency: paymentIntent.currency,
    payerUserId: paymentIntent.metadata.payerUserId ? Number(paymentIntent.metadata.payerUserId) : null,
    payeeUserId: paymentIntent.metadata.payeeUserId ? Number(paymentIntent.metadata.payeeUserId) : null,
    rawStatus: paymentIntent.status,
    source: "stripe",
  });
  const contract = db.prepare("SELECT * FROM contracts WHERE id = ?").get(contractId);
  const payerUserId = paymentIntent.metadata.payerUserId ? Number(paymentIntent.metadata.payerUserId) : null;
  const payer = payerUserId ? db.prepare("SELECT * FROM users WHERE id = ?").get(payerUserId) : null;
  if (payer) {
    sendMail({
      to: payer.email,
      subject: `Payment failed: ${contract.name}`,
      text: `Your payment on "${contract.name}" did not go through. Open the contract on Pact to try again.`,
    });
  }
}

function handleChargeRefunded(charge, stripeEventId) {
  const contractId = Number(charge.metadata && charge.metadata.contractId);
  if (!contractId) return;
  const event = recordPaymentEvent({
    contractId,
    eventType: "refunded",
    stripeEventId,
    stripePaymentIntentId: charge.payment_intent,
    amountCents: charge.amount_refunded,
    currency: charge.currency,
    rawStatus: charge.status,
    source: "stripe",
  });
  recomputeContractPaymentStatus(contractId);
  const contract = db.prepare("SELECT * FROM contracts WHERE id = ?").get(contractId);
  emailBothParties(contractId, {
    subject: `Refund issued: ${contract.name}`,
    text: `A refund of ${(event.amount_cents / 100).toFixed(2)} ${event.currency.toUpperCase()} was issued on "${contract.name}". Status: ${STATUS_LABEL[contract.payment_status]}.`,
  });
}

function handleDisputeCreated(dispute, stripeEventId) {
  const contractId = Number(dispute.metadata && dispute.metadata.contractId);
  if (!contractId) return;
  recordPaymentEvent({
    contractId,
    eventType: "dispute_created",
    stripeEventId,
    stripePaymentIntentId: dispute.payment_intent,
    amountCents: dispute.amount,
    currency: dispute.currency,
    rawStatus: dispute.status,
    source: "stripe",
  });
  db.prepare("UPDATE contracts SET payment_status = 'disputed' WHERE id = ?").run(contractId);
  reopenIfDisputed(contractId);
  const contract = db.prepare("SELECT * FROM contracts WHERE id = ?").get(contractId);
  emailBothParties(contractId, {
    subject: `Payment disputed: ${contract.name}`,
    text: `A payment dispute was opened on "${contract.name}". If this contract had auto-closed on full payment, it has been reopened pending resolution.`,
  });
}

function handleDisputeClosed(dispute, stripeEventId) {
  const contractId = Number(dispute.metadata && dispute.metadata.contractId);
  if (!contractId) return;
  const won = dispute.status === "won";
  recordPaymentEvent({
    contractId,
    eventType: won ? "dispute_won" : "dispute_lost",
    stripeEventId,
    stripePaymentIntentId: dispute.payment_intent,
    amountCents: won ? 0 : dispute.amount,
    currency: dispute.currency,
    rawStatus: dispute.status,
    source: "stripe",
  });
  recomputeContractPaymentStatus(contractId);
  const contract = db.prepare("SELECT * FROM contracts WHERE id = ?").get(contractId);
  emailBothParties(contractId, {
    subject: `Payment dispute resolved: ${contract.name}`,
    text: `The payment dispute on "${contract.name}" was resolved (${won ? "won" : "lost"} by the payee). Status: ${STATUS_LABEL[contract.payment_status]}.`,
  });
}

// ---- "Paid outside Pact" mutual confirmation ----

function proposeOffPlatformPayment(contract, actingUser, { amountCents, note }) {
  const amt = Number(amountCents);
  if (!Number.isInteger(amt) || amt <= 0) {
    const err = new Error("Amount must be a positive whole number of cents.");
    err.status = 400;
    throw err;
  }
  const existing = db.prepare("SELECT * FROM off_platform_payment_confirmations WHERE contract_id = ? AND confirmed_at IS NULL").get(contract.id);
  if (existing) {
    const err = new Error("There is already a pending off-platform payment proposal awaiting the other party's confirmation.");
    err.status = 409;
    throw err;
  }
  db.prepare(
    "INSERT INTO off_platform_payment_confirmations (contract_id, proposed_by_user_id, amount_cents, note) VALUES (?, ?, ?, ?)"
  ).run(contract.id, actingUser.id, amt, note || null);
  logAudit(contract.id, actingUser, "off_platform_payment_proposed", `${actingUser.name} proposed marking ${(amt / 100).toFixed(2)} as paid outside Pact.`);
}

function confirmOffPlatformPayment(contract, actingUser) {
  const proposal = db.prepare("SELECT * FROM off_platform_payment_confirmations WHERE contract_id = ? AND confirmed_at IS NULL").get(contract.id);
  if (!proposal) {
    const err = new Error("No pending off-platform payment proposal to confirm.");
    err.status = 404;
    throw err;
  }
  if (proposal.proposed_by_user_id === actingUser.id) {
    const err = new Error("The other party must confirm this proposal — you can't confirm your own.");
    err.status = 403;
    throw err;
  }
  db.prepare("UPDATE off_platform_payment_confirmations SET confirmed_by_user_id = ?, confirmed_at = datetime('now') WHERE id = ?").run(
    actingUser.id,
    proposal.id
  );
  recordPaymentEvent({
    contractId: contract.id,
    eventType: "off_platform_confirmed",
    amountCents: proposal.amount_cents,
    currency: (getPaymentTerms(contract.id) || {}).currency || "usd",
    source: "off_platform_confirmed",
    createdByUserId: actingUser.id,
  });
  recomputeContractPaymentStatus(contract.id);
  logAudit(contract.id, actingUser, "off_platform_payment_confirmed", `${actingUser.name} confirmed the off-platform payment — labeled "Paid, confirmed by both parties (off-platform)".`);
}

// ---- Rate limiting (payment-request creation) ----
// In-memory and per-process is enough here: this service runs as a single
// Render "starter" plan instance, same assumption the rest of this
// codebase's lockout/throttle logic already makes (see users.
// failed_login_attempts). A restart simply resets the window.
const REQUEST_WINDOW_MS = 60 * 60 * 1000;
const REQUEST_MAX_PER_WINDOW = 20;
const requestTimestamps = new Map();

function checkPaymentRequestRateLimit(userId) {
  const now = Date.now();
  const timestamps = (requestTimestamps.get(userId) || []).filter((t) => now - t < REQUEST_WINDOW_MS);
  if (timestamps.length >= REQUEST_MAX_PER_WINDOW) {
    const err = new Error("Too many payment requests created recently — try again later.");
    err.status = 429;
    throw err;
  }
  timestamps.push(now);
  requestTimestamps.set(userId, timestamps);
}

function computeApplicationFeeCents(amountCents) {
  const pct = Number(process.env.PLATFORM_FEE_PERCENT || 0);
  if (!pct) return 0;
  return Math.round(amountCents * (pct / 100));
}

